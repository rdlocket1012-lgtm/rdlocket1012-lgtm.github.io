/**
 * Indices into LIVE_PROMPTS for a given category (or the whole set if unknown).
 * When `level` is given (After Dark), only prompts at that exact spice tier are
 * returned — both phones stay in sync because the host shares the resulting
 * concrete indices, not the level.
 */
export function categoryIndices(catId?: string | null, level?: 1 | 2 | 3 | null): number[] {
  if (!catId) {
    // "Play everything" (e.g. the online banner) excludes the tiered After Dark
    // deck — explicit prompts are only reachable through its spice picker.
    const out: number[] = [];
    LIVE_PROMPTS.forEach((p, i) => { if (p.level == null) out.push(i); });
    return out;
  }
  let offset = 0;
  for (const c of LIVE_CATEGORIES) {
    if (c.id === catId) {
      const out: number[] = [];
      c.prompts.forEach((p, i) => {
        if (level == null || p.level === level) out.push(offset + i);
      });
      return out;
    }
    offset += c.prompts.length;
  }
  return LIVE_PROMPTS.map((_, i) => i);
}

/** Which category a flat index belongs to — both phones derive this identically. */
export function categoryOfIndex(i: number): LiveCategory | null {
  let offset = 0;
  for (const c of LIVE_CATEGORIES) {
    if (i < offset + c.prompts.length) return c;
    offset += c.prompts.length;
  }
  return null;
}

/** Replace {p1}/{p2} name tokens. name1/name2 must be in a stable shared order. */
export function fillNames(text: string, name1: string, name2: string): string {
  return text.replace(/\{p1\}/g, name1).replace(/\{p2\}/g, name2);
}
